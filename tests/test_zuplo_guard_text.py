"""Zuplo export spec invariants 2 and 3 and 4.4 (header paragraph): `GUARD_TS` and `CHECK_MJS` are ASCII text with the
engine version in their header and nothing from a pack, the guard imports nothing at runtime and uses erasable TypeScript
syntax only, and Node can read both files. What the guard and the script do is claimed by `tests/node/` and
`tests/test_zuplo_vectors.py`."""
from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import pytest

from spellwarden_scan import __version__
from spellwarden_scan.exports.zuplo_guard import CHECK_MJS, GUARD_TS

ERASABLE = re.compile(r"^\s*(?:export\s+)?(?:const\s+)?enum\s|^\s*(?:export\s+)?(?:declare\s+)?namespace\s|constructor\s*\(\s*(?:private|public|protected|readonly)\s")


def test_both_files_are_ascii_with_the_engine_version_in_the_header():
    for text in (GUARD_TS, CHECK_MJS):
        text.encode("ascii")
        assert "__ENGINE_VERSION__" not in text
        assert f"Generated by Spellwarden {__version__}." in "\n".join(text.splitlines()[:6])
    assert "Do not edit: spellwarden-zuplo-check.mjs verifies this file's SHA-256." in GUARD_TS


def test_the_guard_imports_only_types_and_uses_erasable_syntax():
    imports = [line for line in GUARD_TS.splitlines() if re.match(r"\s*import\b", line)]
    assert imports == ['import type { ZuploContext, ZuploRequest } from "@zuplo/runtime";']
    assert not any(ERASABLE.search(line) for line in GUARD_TS.splitlines())
    assert "require(" not in GUARD_TS and "import(" not in GUARD_TS and "fetch(" not in GUARD_TS


def test_the_check_script_uses_only_node_modules():
    modules = re.findall(r'from "([^"]+)"', CHECK_MJS)
    assert sorted(modules) == ["node:crypto", "node:fs", "node:path"]


def test_the_two_files_are_the_same_for_every_caller():
    from spellwarden_scan.exports import zuplo_guard

    assert zuplo_guard.GUARD_TS == GUARD_TS and zuplo_guard.CHECK_MJS == CHECK_MJS


@pytest.mark.skipif(shutil.which("node") is None, reason="Node is not installed (make check-node needs it)")
def test_node_reads_both_files(tmp_path: Path):
    check = tmp_path / "check.mjs"
    check.write_bytes(CHECK_MJS.encode("ascii"))
    done = subprocess.run(["node", "--check", str(check)], capture_output=True, text=True, check=False)
    assert done.returncode == 0, done.stderr
