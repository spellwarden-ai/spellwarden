"""Writes `tests/fixtures/a2a/proto/a2a-v1.0.1-card.proto`: the messages of `specification/a2a.proto` that an agent card
is made of, copied from the tag `v1.0.1` of github.com/a2aproject/A2A (commit 3303592) without their comments, under a
header line that names the commit. Run once; the committed file is what `tests/test_a2a_signing.py` compares the
`_PRESENCE` table of `spellwarden_scan.a2a_signing` to (claim S8).

    python scripts/extract_card_proto.py > tests/fixtures/a2a/proto/a2a-v1.0.1-card.proto
"""
from __future__ import annotations

import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/a2aproject/A2A/3303592/specification/a2a.proto"
MESSAGES = ("AgentInterface", "AgentCard", "AgentProvider", "AgentCapabilities", "AgentExtension", "AgentSkill",
            "AgentCardSignature", "StringList", "SecurityRequirement", "SecurityScheme", "APIKeySecurityScheme",
            "HTTPAuthSecurityScheme", "OAuth2SecurityScheme", "OpenIdConnectSecurityScheme", "MutualTlsSecurityScheme",
            "OAuthFlows", "AuthorizationCodeOAuthFlow", "ClientCredentialsOAuthFlow", "ImplicitOAuthFlow",
            "PasswordOAuthFlow", "DeviceCodeOAuthFlow")


def main() -> None:
    with urllib.request.urlopen(URL, timeout=30) as response:  # noqa: S310 -- a fixed https URL
        source = response.read().decode("utf-8")
    out = ["// Excerpt of specification/a2a.proto, github.com/a2aproject/A2A tag v1.0.1, commit 3303592: the messages an agent",
           "// card is made of, without their comments. Generated by scripts/extract_card_proto.py.", ""]
    for name in MESSAGES:
        match = re.search(rf"^message {name} \{{\n.*?^\}}\n", source, re.M | re.S)
        if match is None:
            sys.exit(f"message {name} not found")
        lines = [line for line in match.group(0).splitlines() if line.strip() and not line.strip().startswith("//")]
        out.extend(lines + [""])
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
