#!/usr/bin/env python3
"""The framework data of `spellwarden_scan.frameworks` (Phase 3 batch 1 spec 9.1, 9.2, 11.3).

    python scripts/frameworks/build_atlas_scope.py vendor ATLAS-2026.10.yaml   # atlas_techniques.json from the release file
    python scripts/frameworks/build_atlas_scope.py scope                       # atlas_scope.json from it and tests/frameworks_expected.py
    python scripts/frameworks/build_atlas_scope.py data                        # frameworks/_data.py from the three JSON files
    python scripts/frameworks/build_atlas_scope.py docs                        # docs/frameworks.md from the data
    python scripts/frameworks/build_atlas_scope.py all ATLAS-2026.10.yaml      # the four, in this order
    python scripts/frameworks/build_atlas_scope.py check                       # exit 1 when a file differs from what it would write

The engine reads no files (tests/test_pure.py), so `_data.py` holds each JSON file as a string constant, the way
`packs/__init__.py` holds `baseline.json`, and `tests/test_frameworks.py` keeps the constants equal to the files.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "src" / "spellwarden_scan" / "frameworks"
DOCS = ROOT / "docs" / "frameworks.md"
FILES = (("ATLAS_TECHNIQUES_JSON", "atlas_techniques.json"), ("ATLAS_SCOPE_JSON", "atlas_scope.json"),
         ("FRAMEWORKS_JSON", "frameworks.json"))
SCOPE_WORD = "Agent"


def _j(value: object) -> str:
    return json.dumps(value, sort_keys=True, ensure_ascii=True)


def techniques_text(yaml_text: str) -> str:
    """`atlas_techniques.json`: every technique and sub-technique of the release with its own name, one per line. A
    sub-technique (`AML.T0051.001`) names its parent (`AML.T0051`); its full name is `<parent name>: <own name>`."""
    import yaml

    document = yaml.safe_load(yaml_text)
    entries = {}
    for identifier, entry in document["techniques"].items():
        item = {"name": entry["name"]}
        if identifier.count(".") > 1:
            item["parent"] = identifier.rsplit(".", 1)[0]
        entries[identifier] = item
    lines = ["{", f' "format_version": {_j(document["format-version"])},', f' "modified": {_j(document["collection"]["modified-date"])},',
             f' "release": {_j(document["collection"]["version"])},', ' "techniques": {']
    lines.append(",\n".join(f"  {_j(identifier)}: {_j(entries[identifier])}" for identifier in sorted(entries)))
    lines += [" }", "}"]
    return "\n".join(lines) + "\n"


def full_name(techniques: dict, identifier: str) -> str:
    entry = techniques[identifier]
    parent = entry.get("parent")
    return f"{techniques[parent]['name']}: {entry['name']}" if parent else entry["name"]


def scope_text(techniques_document: dict, used: set[str]) -> str:
    """`atlas_scope.json`: the ids the crosswalk page lists (spec 9.2): every id whose full name contains "Agent", plus
    every id a rule uses, sorted. "No rule covers it" has a definition because of this list."""
    techniques = techniques_document["techniques"]
    ids = {identifier for identifier in techniques if SCOPE_WORD in full_name(techniques, identifier)} | set(used)
    unknown = sorted(ids - set(techniques))
    if unknown:
        raise SystemExit(f"ids that are not in release {techniques_document['release']}: {', '.join(unknown)}")
    return json.dumps({"release": techniques_document["release"], "ids": sorted(ids)}, indent=1, sort_keys=True) + "\n"


def data_text() -> str:
    parts = ['"""Generated by scripts/frameworks/build_atlas_scope.py: the three JSON files of this package as string constants,\n'
             'because the engine reads no files (tests/test_pure.py). tests/test_frameworks.py keeps each constant equal to its file."""\n',
             "from __future__ import annotations\n"]
    for name, filename in FILES:
        text = (PACKAGE / filename).read_text(encoding="utf-8").replace("\r\n", "\n")
        if '"""' in text:
            raise SystemExit(f"{filename} holds three double quotes in a row")
        parts.append(f'\n{name} = r"""{text}"""\n')
    return "".join(parts)


def used_ids() -> set[str]:
    """The ATLAS ids the rules use, from `tests/frameworks_expected.py` (a test keeps the rules equal to that table)."""
    sys.path.insert(0, str(ROOT / "tests"))
    from frameworks_expected import EXPECTED

    return {identifier for atlas, _ast in EXPECTED.values() for identifier in atlas}


def docs_text() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from spellwarden_scan import frameworks
    from spellwarden_scan.rules import RuleSet

    rows = []
    for rule in RuleSet.baseline():
        atlas = "; ".join(f"{identifier} {frameworks.ATLAS_TECHNIQUES[identifier]}" for identifier in rule.atlas)
        if not rule.atlas:
            atlas = f"no technique ({frameworks.NO_ATLAS[rule.id]})"
        rows.append(f"| {rule.id} | {atlas} | {', '.join(rule.owasp_ast) or 'none'} |")
    ast = frameworks.FRAMEWORKS["owasp_ast"]
    atlas = frameworks.FRAMEWORKS["atlas"]
    return "\n".join([
        "# Framework tags",
        "",
        "Every rule carries MITRE ATLAS technique ids and OWASP Agentic Skills Top 10 ids next to its OWASP Agentic Top 10, OWASP MCP",
        "Top 10 and NIST SP 800-53 tags. This file records what each rule is tagged with and where the lists come from. The data is in",
        "`src/spellwarden_scan/frameworks/`; this file is written from it by `scripts/frameworks/build_atlas_scope.py docs`.",
        "",
        "## Versions",
        "",
        "| Tag | Framework | Version | Source |",
        "|---|---|---|---|",
        f"| atlas | {atlas.name} | content release {atlas.version}, data format {frameworks.ATLAS_FORMAT_VERSION}, "
        f"modified {frameworks.ATLAS_MODIFIED} | github.com/mitre-atlas/atlas-data, file dist/v6/ATLAS-{atlas.version}.yaml |",
        f"| owasp_ast | {ast.name} | {ast.version}, {ast.status} | {ast.url} |",
        "",
        "An empty ATLAS column means no technique fits the rule; the reason is in the table below and in `NO_ATLAS`. The ATLAS",
        f"file has no deprecation marker, so \"not deprecated\" means \"present in release {atlas.version}\".",
        "",
        "## Mapping",
        "",
        "| Rule | MITRE ATLAS | OWASP AST |",
        "|---|---|---|",
        *rows,
        "",
        "## Review record",
        "",
        "The mapping was drafted from the rule titles. Each row was read against the rule's title and the description of each",
        f"technique in ATLAS {atlas.version} (the descriptions printed from the release file). Corrections made after that reading:",
        "none. The OWASP AST column is the mapping spellwarden.ai already published, carried over row for row.",
        "A correction to a row is made in `tests/frameworks_expected.py`, in the rule's `make_rule` call and here, with the reason.",
    ]) + "\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote {path.relative_to(ROOT).as_posix()}")


def run_vendor(yaml_path: str) -> None:
    write(PACKAGE / "atlas_techniques.json", techniques_text(Path(yaml_path).read_text(encoding="utf-8")))


def run_scope() -> None:
    document = json.loads((PACKAGE / "atlas_techniques.json").read_text(encoding="utf-8"))
    write(PACKAGE / "atlas_scope.json", scope_text(document, used_ids()))


def run_data() -> None:
    write(PACKAGE / "_data.py", data_text())


def run_docs() -> None:
    write(DOCS, docs_text())


def run_check() -> int:
    document = json.loads((PACKAGE / "atlas_techniques.json").read_text(encoding="utf-8"))
    expected = {PACKAGE / "atlas_scope.json": scope_text(document, used_ids()), PACKAGE / "_data.py": data_text(), DOCS: docs_text()}
    stale = [path for path, text in expected.items() if path.read_bytes().decode("utf-8").replace("\r\n", "\n") != text]
    for path in stale:
        print(f"stale: {path.relative_to(ROOT).as_posix()}")
    return 1 if stale else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("vendor", "scope", "data", "docs", "all", "check"))
    parser.add_argument("yaml", nargs="?", help="the ATLAS release file (vendor and all)")
    args = parser.parse_args(argv)
    if args.command in ("vendor", "all"):
        if args.yaml is None:
            parser.error("vendor and all need the ATLAS release file")
        run_vendor(args.yaml)
    if args.command in ("scope", "all"):
        run_scope()
    if args.command in ("data", "all"):
        run_data()
    if args.command in ("docs", "all"):
        run_docs()
    return run_check() if args.command == "check" else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
